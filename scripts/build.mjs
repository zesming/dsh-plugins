/**
 * Build the plugin's Host entry and browser bundle.
 *
 * The browser artifact must be a single lazy factory registered on
 * `window.__ModuleLoader__`; `bun build` produces the CommonJS body from the
 * ESM sources and this script wraps it in that registration.
 */

import { mkdir, writeFile } from 'node:fs/promises'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import path from 'node:path'

const run = promisify(execFile)

/** Repository root. */
const root = path.resolve(import.meta.dirname, '..')

/** The one package this repository builds today. */
const pkg = path.join(root, 'packages', 'dsh-deepseek-usage')

/** Locate `bun`, which the repository uses as its bundler. */
async function bunBinary() {
  try {
    const { stdout } = await run('which', ['bun'])
    return stdout.trim()
  } catch {
    throw new Error('bun is required to build the browser bundle (https://bun.sh)')
  }
}

/**
 * Bundle one entry into a CommonJS body.
 *
 * @param bun - bun executable path.
 * @param entry - absolute entry path.
 * @returns bundled source.
 */
async function bundle(bun, entry, format, target, external) {
  const args = ['build', entry, '--format', format, '--target', target]
  for (const name of external) args.push('--external', name)
  const { stdout } = await run(bun, args, { maxBuffer: 32 * 1024 * 1024 })
  return stdout
}

/**
 * Wrap a CommonJS body in the loader's factory registration.
 *
 * @param id - package name the factory registers under.
 * @param body - CommonJS source from bun.
 * @returns the browser artifact.
 */
function wrapFactory(id, body) {
  return `// Generated by scripts/build.mjs — edit src/**/*.js instead.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(id)},
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    // The host may hand us React as a CommonJS object or as an ES module
    // namespace, and the bundled code reaches it through the CJS interop
    // helper, which reads the default export. Normalize once so both shapes work.
    const rawReact = require('react');
    const React = rawReact.default ?? rawReact;
    const reactRequire = id => (id === 'react' ? React : require(id));
    ;(function (module, exports, require) {
${body}
    })(module, exports, reactRequire);
    return { inject: module.exports.inject, apply: module.exports.apply };
  },
});
`
}

const bun = await bunBinary()
await mkdir(path.join(pkg, 'lib'), { recursive: true })

const clientBody = await bundle(bun, path.join(pkg, 'src', 'client.js'), 'cjs', 'browser', ['react'])
await writeFile(path.join(pkg, 'lib', 'client.js'), wrapFactory('dsh-deepseek-usage', clientBody))

// The Host entry stays a real ES module: the package is `type: module` and the
// loader imports it directly.
const hostBody = await bundle(bun, path.join(pkg, 'src', 'index.js'), 'esm', 'node', [])
await writeFile(path.join(pkg, 'lib', 'index.js'), `// Generated by scripts/build.mjs — edit src/index.js instead.\n${hostBody}`)

process.stdout.write(`built ${path.relative(root, pkg)}\n`)
