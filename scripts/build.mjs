/**
 * Build every package's Host entry and browser bundle.
 *
 * The browser artifact must be a single lazy factory registered on
 * `window.__ModuleLoader__`; `bun build` produces the CommonJS body from the
 * ESM sources and this script wraps it in that registration.
 *
 * Pass package names to build only those packages, e.g.
 * `node scripts/build.mjs dsh-conversation-assist`. With no arguments every
 * package under `packages/` is built.
 */

import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { execFile } from 'node:child_process'
import { promisify } from 'node:util'
import path from 'node:path'

const run = promisify(execFile)

/** Repository root. */
const root = path.resolve(import.meta.dirname, '..')

/** Optional package filters from the command line. */
const requested = process.argv.slice(2).filter(argument => !argument.startsWith('-'))

/** Locate `bun`, which the repository uses as its bundler. */
async function bunBinary() {
  try {
    const { stdout } = await run('which', ['bun'])
    return stdout.trim()
  } catch {
    throw new Error('bun is required to build the browser bundle (https://bun.sh)')
  }
}

/**
 * Bundle one entry into a CommonJS or ESM body.
 *
 * @param bun - bun executable path.
 * @param entry - absolute entry path.
 * @param format - `cjs` or `esm`.
 * @param target - `browser` or `node`.
 * @param external - module specifiers kept out of the bundle.
 * @returns bundled source.
 */
async function bundle(bun, entry, format, target, external) {
  const args = ['build', entry, '--format', format, '--target', target]
  for (const name of external) args.push('--external', name)
  const { stdout } = await run(bun, args, { maxBuffer: 32 * 1024 * 1024 })
  return stdout
}

/**
 * Wrap a CommonJS body in the loader's factory registration.
 *
 * @param id - package name the factory registers under.
 * @param body - CommonJS source from bun.
 * @returns the browser artifact.
 */
function wrapFactory(id, body) {
  return `// Generated by scripts/build.mjs — edit src/**/*.js instead.
window.__ModuleLoader__.load({
  id: ${JSON.stringify(id)},
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
    // The host may hand us React as a CommonJS object or as an ES module
    // namespace, and the bundled code reaches it through the CJS interop
    // helper, which reads the default export. Normalize once so both shapes work.
    const rawReact = require('react');
    const React = rawReact.default ?? rawReact;
    const reactRequire = id => (id === 'react' ? React : require(id));
    ;(function (module, exports, require) {
${body}
    })(module, exports, reactRequire);
    return { inject: module.exports.inject, apply: module.exports.apply };
  },
});
`
}

/**
 * Read the packages this invocation should build.
 * @returns package directories and parsed manifests.
 */
async function selectedPackages() {
  const entries = await readdir(path.join(root, 'packages'), { withFileTypes: true })
  const packages = []
  for (const entry of entries) {
    if (!entry.isDirectory()) continue
    const dir = path.join(root, 'packages', entry.name)
    const manifest = JSON.parse(await readFile(path.join(dir, 'package.json'), 'utf8'))
    if (requested.length > 0 && !requested.includes(manifest.name) && !requested.includes(entry.name)) continue
    packages.push({ dir, manifest })
  }
  return packages
}

const bun = await bunBinary()
const packages = await selectedPackages()
if (packages.length === 0) throw new Error('no packages selected')

for (const { dir, manifest } of packages) {
  const name = manifest.name
  if (typeof name !== 'string' || name === '') throw new Error(`${dir}: package.json needs a name`)
  if (path.basename(dir) !== name) throw new Error(`${dir}: directory name must equal the package name`)
  const hostEntry = path.join(dir, 'src', 'index.js')
  const clientEntry = path.join(dir, 'src', 'client.js')
  if (!existsSync(hostEntry) && !existsSync(clientEntry)) throw new Error(`${dir}: no src entry`)
  await mkdir(path.join(dir, 'lib'), { recursive: true })

  if (existsSync(clientEntry)) {
    // Primitives come from the host's shared module table, so they stay
    // external: bundling a second copy would break the menu's theme tokens and
    // focus ring. Every package declares its own extra externals.
    const external = ['react', ...(manifest?.dsh?.client?.external ?? [])]
    const body = await bundle(bun, clientEntry, 'cjs', 'browser', external)
    // A second copy of a shared module would lose theme tokens and focus rings;
    // fail the build instead of shipping it when a package forgets an external.
    const required = new Set([...body.matchAll(/require\((['"])([^'"]+)\1\)/gu)].map(match => match[2]))
    for (const specifier of required) {
      if (specifier === 'react' || external.includes(specifier)) continue
      throw new Error(`${name}: client bundle requires "${specifier}" outside react and dsh.client.external`)
    }
    await writeFile(path.join(dir, 'lib', 'client.js'), wrapFactory(name, body))
  }

  if (existsSync(hostEntry)) {
    const body = await bundle(bun, hostEntry, 'esm', 'node', [])
    await writeFile(path.join(dir, 'lib', 'index.js'), `// Generated by scripts/build.mjs — edit src/index.js instead.\n${body}`)
  }

  process.stdout.write(`built ${name}\n`)
}
